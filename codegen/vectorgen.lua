#!/usr/bin/env lua
-- Generate Serenity's named vector aliases and convenience constructors.

local function fail(message) error("vectorgen: " .. message, 0) end
local output
local dimensions
local i = 1
while i <= #arg do
    if arg[i] == "-o" or arg[i] == "--output" then
        output = arg[i + 1]
        if not output then fail("missing output path") end
        i = i + 1
    elseif arg[i] == "--dimensions" then
        dimensions = arg[i + 1]
        if not dimensions then fail("missing vector dimensions") end
        i = i + 1
    else
        fail("unexpected argument '" .. arg[i] .. "'")
    end
    i = i + 1
end
if not output or not dimensions then fail("usage: vectorgen.lua --dimensions 2,3,4 -o OUTPUT") end

local sizes, seen = {}, {}
for value in dimensions:gmatch("[^,]+") do
    local n = tonumber(value)
    if not n or n < 2 or n > 4 or n % 1 ~= 0 then fail("unsupported vector dimension '" .. value .. "' (expected 2, 3, or 4)") end
    if seen[n] then fail("duplicate vector dimension " .. value) end
    seen[n] = true
    sizes[#sizes + 1] = n
end
if #sizes == 0 then fail("at least one vector dimension is required") end
table.sort(sizes)

local function write(path, content)
    local parent = path:match("^(.*)/[^/]+$")
    if parent then os.execute("mkdir -p " .. string.format("%q", parent)) end
    local file, err = io.open(path, "wb")
    if not file then fail(err) end
    file:write(content)
    file:close()
end

local out = {"// Generated by serenity-vectorgen. Do not edit.\n#pragma once\n#include \"vec.hpp\"\n\nnamespace serenity { namespace math {\n"}
for _, n in ipairs(sizes) do
    local coords = {"x", "y", "z", "t"}
    local args, assignments = {}, {}
    for i = 1, n do
        args[i] = "T " .. coords[i]
        assignments[i] = "res[math::" .. coords[i] .. "] = " .. coords[i] .. ";"
    end
    out[#out + 1] = string.format("template <typename T> using Vec%d = Vec<%d, T>;\n", n, n)
    for _, suffix in ipairs({"i", "f", "d", "u"}) do
        local typ = ({i="int", f="float", d="double", u="unsigned int"})[suffix]
        out[#out + 1] = string.format("using Vec%d%s = Vec%d<%s>;\n", n, suffix, n, typ)
    end
    out[#out + 1] = string.format("template <typename T> inline Vec%d<T> vec%d(%s) { Vec%d<T> res; %s return res; }\n\n", n, n, table.concat(args, ", "), n, table.concat(assignments, " "))
end
if seen[2] and seen[4] then out[#out + 1] = [[template <typename T>
inline Vec4<T> vec4(Vec2<T> v1, Vec2<T> v2) {
	Vec4<T> res;
	res[x] = v1[x]; res[y] = v1[y]; res[z] = v2[x]; res[t] = v2[y];
	return res;
}

}}
]]
else out[#out + 1] = "}}\n" end
write(output, table.concat(out))
