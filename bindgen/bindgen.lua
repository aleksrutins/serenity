#!/usr/bin/env lua
-- Generate sol2 Lua bindings from Serenity's C++-oriented IDL.

local script = arg[0]:gsub("\\", "/")
local directory = script:match("^(.*)/") or "."
package.path = directory .. "/?.lua;" .. package.path

local Parser = require("parser")
local emit = require("emitter")

local function fail(message)
    error(message, 0)
end

local function read_file(path)
    local file, err = io.open(path, "rb")
    if not file then fail(err) end
    local content = file:read("*a")
    file:close()
    return content
end

local function write_file(path, content)
    local parent = path:match("^(.*)/[^/]+$")
    if parent then os.execute("mkdir -p " .. string.format("%q", parent)) end
    local file, err = io.open(path, "wb")
    if not file then fail(err) end
    file:write(content)
    file:close()
end

local function main(argv)
    local input, output
    local i = 1
    while i <= #argv do
        if argv[i] == "-o" or argv[i] == "--output" then
            output = argv[i + 1]
            i = i + 2
        elseif not input then
            input = argv[i]
            i = i + 1
        else
            fail("unexpected argument '" .. argv[i] .. "'")
        end
    end
    if not input or not output then fail("usage: bindgen.lua INPUT -o OUTPUT") end
    local ok, result = pcall(function()
        return emit(Parser.new(read_file(input)):parse())
    end)
    if not ok then
        io.stderr:write("bindgen: " .. tostring(result) .. "\n")
        return 1
    end
    write_file(output, "// Generated by serenity-bindgen. Do not edit.\n" .. result)
    return 0
end

os.exit(main(arg))
